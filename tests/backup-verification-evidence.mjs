import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { sealVerificationEvidence,openVerificationEvidence,validateVerificationEvidence,verificationMode,matchingVerifiedObject } from '../scripts/backup-verification-evidence.mjs';
import { backupBucketId } from '../scripts/backup-storage.mjs';
const now=Date.parse('2026-09-22T12:00:00Z'),at=new Date(now).toISOString(),key=randomBytes(32);
const record={fileId:'pinned-version',fileName:'relay/originals/'+ 'a'.repeat(64),size:100,sha256:'a'.repeat(64),verifiedAt:at};
const evidence={formatVersion:1,bucketId:backupBucketId,mode:'full',verifiedAt:at,fullVerifiedAt:at,objects:[record]};
const sealed=sealVerificationEvidence(evidence,key,'123');
assert.deepEqual(validateVerificationEvidence(openVerificationEvidence(sealed,key,'123'),now),evidence);
assert.throws(()=>openVerificationEvidence(sealed,key,'124'));
assert.throws(()=>openVerificationEvidence(sealed,randomBytes(32),'123'));
const corrupt=Buffer.from(sealed);corrupt[30]^=1;assert.throws(()=>openVerificationEvidence(corrupt,key,'123'));
assert.throws(()=>validateVerificationEvidence({...evidence,bucketId:'other'},now));
assert.throws(()=>validateVerificationEvidence({...evidence,objects:[record,record]},now));
assert.throws(()=>validateVerificationEvidence({...evidence,objects:[{...record,fileName:'elsewhere'}]},now));
assert.throws(()=>validateVerificationEvidence(evidence,now+36*86400000));
assert.equal(verificationMode('auto',evidence,now),'incremental');
assert.equal(verificationMode('full',evidence,now),'full');
assert.equal(verificationMode('auto',null,now),'full');
assert.equal(verificationMode('auto',evidence,Date.parse('2026-10-01')),'full');
assert.equal(matchingVerifiedObject(record,evidence),record);
for(const changes of [{fileId:'new-version'},{size:101},{sha256:'b'.repeat(64)},{fileName:'other'}])assert.equal(matchingVerifiedObject({...record,...changes},evidence),undefined);
console.log('PASS: encrypted verifier-only evidence rejects tampering, wrong run/key/bucket, stale/duplicate records and changed versions; monthly/full fallback enforced.');
