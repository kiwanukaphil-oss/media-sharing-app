import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium, firefox, webkit, expect } from '@playwright/test';
const origin = process.env.RELAY_TEST_ORIGIN || 'http://127.0.0.1:8812';
assert.ok(['localhost', '127.0.0.1'].includes(new URL(origin).hostname));
const engine = process.env.RELAY_STORAGE_BROWSER || 'chromium';
const browser = await ({ chromium, firefox, webkit }[engine]).launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const gib = 1024 ** 3;
const usage = { pooled: true, poolUsed: 30 * gib, used: 10 * gib, reserved: 2 * gib, trash: gib, limit: 100 * gib, uploads: [] };
const errors = [];
page.on('pageerror', error => errors.push(error.message));
// Controlled billing snapshots prove remaining-space arithmetic, restricted totals and compact presentation.
await page.route('**/api/**', async route => {
  const path = new URL(route.request().url()).pathname;
  if (path === '/api/auth/session') return route.fulfill({ json: { enabled: false, account: null } });
  if (path === '/api/auth/spaces') return route.fulfill({ json: { spaces: [] } });
  if (path === '/api/session') return route.fulfill({ json: { authentication: 'device', deviceId: 'owner', role: 'owner', transport: 'local', space: { id: 'fixture', name: 'Studio archive', kind: 'shared' } } });
  if (path === '/api/feed') return route.fulfill({ json: { items: [], total: 0, counts: { all: 0, trash: 0 }, role: 'owner' } });
  if (path === '/api/storage') return route.fulfill({ json: usage });
  if (path === '/api/albums') return route.fulfill({ json: { albums: [], sections: [] } });
  if (path === '/api/activity') return route.fulfill({ json: { events: [], next: null } });
  if (path === '/api/devices') return route.fulfill({ json: { devices: [] } });
  throw new Error(`Unexpected storage UI request: ${path}`);
});
try {
  await page.goto(origin);
  const navigation = page.getByRole('button', { name: /^Storage/ });
  await expect(navigation).toContainText('30.0 GB used');
  await expect(navigation).toContainText('70.0 GB available');
  await navigation.click();
  const dialog = page.getByRole('dialog', { name: 'Storage', exact: true });
  await expect(dialog.locator('.storage-available dd')).toHaveText('70.0 GB');
  await expect(dialog.getByRole('progressbar')).toHaveAttribute('value', String(30 * gib));
  await expect(dialog.locator('.storage-library-facts')).toContainText('10.0 GB');
  await expect(dialog.locator('.storage-library-facts')).toContainText('2.0 GB');
  await mkdir('outputs/storage', { recursive: true });
  await dialog.screenshot({ path: `outputs/storage/${engine}-desktop.png` });
  await page.setViewportSize({ width: 320, height: 740 });
  assert.ok(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth));
  await dialog.screenshot({ path: `outputs/storage/${engine}-mobile.png` });
  await dialog.getByRole('button', { name: 'Open Trash' }).click();
  await expect(page.getByRole('heading', { name: 'Trash', exact: true })).toBeVisible();
  await page.setViewportSize({ width: 1440, height: 1000 });
  delete usage.poolUsed;
  await navigation.click();
  await expect(dialog.locator('.storage-available dd')).toHaveText('Unavailable');
  await expect(dialog.getByRole('progressbar')).toHaveCount(0);
  await page.keyboard.press('Escape');
  usage.pooled = false;
  await navigation.click();
  await expect(dialog.locator('.storage-available dd')).toHaveText('90.0 GB');
  await page.keyboard.press('Escape');
  usage.allScopeBilling = 0;
  await navigation.click();
  await expect(dialog.locator('.storage-available dd')).toHaveText('Unavailable');
  await page.keyboard.press('Escape');
  delete usage.allScopeBilling;
  usage.used = 110 * gib;
  await navigation.click();
  await expect(dialog.locator('.storage-available dd')).toHaveText('0 B');
  await expect(dialog.getByRole('progressbar')).toHaveAttribute('value', String(100 * gib));
  await expect(dialog.locator('.storage-usage-caption')).toContainText('110.0 GB used');
  await page.keyboard.press('Escape');
  usage.uploads = [{ id: 'pending', name: 'Pending original.mov', size: gib, deviceName: 'Desktop', canCancel: true }, { id: 'view-only', name: 'Read only upload.mov', size: gib, deviceName: 'Other device', canCancel: false }];
  await navigation.click();
  await expect(dialog.getByRole('button', { name: 'Cancel upload', exact: true })).toHaveCount(1);
  await dialog.getByRole('button', { name: 'Cancel upload', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Cancel this upload?', exact: true })).toBeVisible();
  assert.deepEqual(errors, []);
  console.log(`PASS ${engine}: shared and library capacity, reservation subsets, restricted totals, full allowance, upload permissions, Trash and 320px layout.`);
} finally { await browser.close(); }
