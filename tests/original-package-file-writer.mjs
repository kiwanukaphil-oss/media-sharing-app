import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {Readable} from 'node:stream';
import {pipeline} from 'node:stream/promises';
import {createHash} from 'node:crypto';
import {chromium,expect} from '@playwright/test';
const previewOrigin=process.env.RELAY_TEST_ORIGIN||'http://127.0.0.1:8795';
assert.ok(['localhost','127.0.0.1'].includes(new URL(previewOrigin).hostname));
const streamMiB=Number(process.env.RELAY_PACKAGE_STREAM_MIB||80);assert.ok([80,2048].includes(streamMiB));
const chunk=Buffer.alloc(1024*1024,7),hash=createHash('sha256');for(let n=0;n<streamMiB;n++)hash.update(chunk);
// Serve generated bytes on the application's own test origin. Proxy only the local preview's
// documents/assets; preserve its CSP instead of weakening browser security for the fixture.
const server=createServer((request,response)=>{
  if(request.url==='/original'){
    response.writeHead(200,{'Content-Type':'application/octet-stream','Content-Length':streamMiB*chunk.length});
    void pipeline(Readable.from((function*(){for(let n=0;n<streamMiB;n++)yield chunk;})()),response).catch(()=>{});return;
  }
  void fetch(previewOrigin+request.url).then(async upstream=>{
    const headers=Object.fromEntries([...upstream.headers].filter(([name])=>!['content-encoding','content-length','transfer-encoding'].includes(name)));
    response.writeHead(upstream.status,headers);if(upstream.body)await pipeline(Readable.fromWeb(upstream.body),response);else response.end();
  }).catch(()=>{if(!response.headersSent)response.writeHead(502);response.end();});
});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));const origin=`http://127.0.0.1:${server.address().port}`,sourceUrl=`${origin}/original`;
// A separate temporary persistent profile avoids incognito's artificial storage quota.
// Playwright owns its lifetime; it never opens or modifies the user's normal Chrome profile.
const browser=await chromium.launchPersistentContext('',{headless:true,viewport:{width:390,height:844},...(process.env.CI?{}:{channel:'chrome'})});
const page=await browser.newPage();page.setDefaultTimeout(120000);page.on('console',message=>{if(message.type()==='error')console.error(message.text().slice(0,500));});
const space=crypto.randomUUID(),actor=crypto.randomUUID();
const item={id:crypto.randomUUID(),name:'Shared original.jpg',mime:'image/jpeg',size:streamMiB*chunk.length,sha256:hash.digest('hex'),category:'original',createdAt:Date.now(),deviceName:'Another member',hasPreview:false,revision:0};
let exports=0;
// Substitute only the picker: the sink is Chromium's real disk-backed file writer in this
// disposable origin's private filesystem, not an in-memory mock or a user's existing file.
await page.addInitScript(()=>Object.defineProperty(window,'showSaveFilePicker',{configurable:true,value:async()=>{
  const root=await navigator.storage.getDirectory();return root.getFileHandle('generated-package.zip',{create:true});
}}));
await page.route('**/api/**',async route=>{
  const request=route.request(),url=new URL(request.url());
  if(url.pathname==='/api/auth/spaces')return route.fulfill({json:{spaces:[{id:space,name:'Viewer library',role:'viewer',kind:'shared',actorId:actor}]}});
  assert.equal(url.searchParams.get('space'),space);
  if(url.pathname.endsWith('/link'))return route.fulfill({json:{url:sourceUrl}});
  if(url.pathname==='/api/session')return route.fulfill({json:{authentication:'account',deviceId:actor,role:'viewer',transport:'local',space:{id:space,name:'Viewer library',kind:'shared'}}});
  if(url.pathname==='/api/feed')return route.fulfill({json:{items:[{...item,canEdit:false}],total:1,nextCursor:null,role:'viewer',counts:{all:1,original:1,final:0,trash:0}}});
  if(url.pathname==='/api/albums')return route.fulfill({json:{albums:[],sections:[]}});
  if(url.pathname==='/api/storage')return route.fulfill({json:{used:4,reserved:0,trash:0,limit:100000,uploads:[]}});
  if(url.pathname==='/api/activity')return route.fulfill({json:{events:[],next:null}});
  if(url.pathname==='/api/metadata-export'){
    assert.equal(request.method(),'POST');assert.deepEqual(request.postDataJSON(),{files:[{id:item.id,expectedRevision:0}]});exports++;
    return route.fulfill({json:{format:'relay-metadata',formatVersion:1,includesOriginalBytes:false,files:[{...item,suggestedPath:`files/${item.id}/${item.name}`,albums:[{name:'Reviewed album',section:{name:'Custom section'}}]}]}});
  }
  throw new Error('Unexpected metadata UI request '+url.pathname);
});
try {
  await page.goto(`${origin}/?space=${space}`);
  await page.getByRole('checkbox',{name:/Select loaded files/}).click();
  await expect(page.getByRole('button',{name:'Rename selected',exact:true})).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Move selected to Trash',exact:true})).toHaveCount(0);
  const estimate=await page.evaluate(()=>navigator.storage.estimate());assert.ok(estimate.quota-estimate.usage>item.size*2+16*1024**2,'The disposable origin needs enough quota for commit and abort preservation.');
  await page.getByRole('button',{name:'Download originals',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'Download originals',exact:true});await dialog.getByRole('button',{name:'Create ZIP',exact:true}).click();
  await expect(dialog.getByRole('status').or(dialog.getByRole('alert'))).toHaveText('Package saved. Every original verified.',{timeout:180000});
  const inspect=()=>page.evaluate(async()=>{const file=await (await (await navigator.storage.getDirectory()).getFileHandle('generated-package.zip')).getFile();return {size:file.size,header:Array.from(new Uint8Array(await file.slice(0,4).arrayBuffer())),tail:Array.from(new Uint8Array(await file.slice(-22).arrayBuffer()))};});
  const completed=await inspect();assert.ok(completed.size>item.size);assert.deepEqual(completed.header,[80,75,3,4]);assert.deepEqual(completed.tail.slice(0,4),[80,75,5,6]);assert.equal(exports,2);
  await dialog.getByRole('button',{name:'Create ZIP',exact:true}).click();
  await expect(dialog.getByRole('status')).toHaveText(/Building and verifying package: [1-9][0-9]?%/,{timeout:30000});
  await dialog.getByRole('button',{name:'Cancel package',exact:true}).click();await expect(dialog.getByRole('status')).toHaveText('Package cancelled. No complete package was saved.');
  assert.deepEqual(await inspect(),completed,'Aborted replacement preserves the previously committed generated archive.');
  console.log(`PASS real browser file writer: ${streamMiB} MiB streamed ZIP committed, bounded HTTP fixture, complete directory, cancellation preserves prior committed file`);
} finally {await browser.close();server.closeAllConnections();await new Promise(resolve=>server.close(resolve));}
