import assert from 'node:assert/strict';
import { randomUUID, createHash } from 'node:crypto';

const origin = process.env.RELAY_TEST_ORIGIN || 'http://127.0.0.1:8787';
if (!['localhost', '127.0.0.1'].includes(new URL(origin).hostname)) throw new Error('Sections require isolated storage.');
const api = (path, cookie, method = 'GET', body) => fetch(`${origin}/api/${path}`, { method, headers: { Origin: origin, Cookie: cookie, 'Content-Type': 'application/json' }, body: body ? JSON.stringify(body) : undefined });
const json = async response => { assert.equal(response.status, 200, await response.clone().text()); return response.json(); };
const owner = (await api('connect', '', 'POST', { name: 'Section owner' })).headers.get('set-cookie').split(';')[0];
const outsider = (await api('connect', '', 'POST', { name: 'Other space' })).headers.get('set-cookie').split(';')[0];
const invite = await json(await api('invitations', owner, 'POST'));
const member = (await api('connect', '', 'POST', { name: 'Section contributor', invitation: invite.token })).headers.get('set-cookie').split(';')[0];
const album = await json(await api('albums', owner, 'POST', { name: 'Event' }));
const secondAlbum = await json(await api('albums', owner, 'POST', { name: 'Portfolio' }));
const albumState = async id => (await json(await api('albums', owner))).albums.find(album => album.id === id);
const createSection = async (albumId, name) => json(await api('sections', owner, 'POST', { albumId, name, expectedRevision: (await albumState(albumId)).revision }));
const ceremony = await createSection(album.id, 'Ceremony');
const shortlist = await createSection(album.id, 'Shortlist');
const portfolio = await createSection(secondAlbum.id, 'Highlights');
assert.equal((await api('sections', member, 'POST', { albumId: album.id, name: 'Denied', expectedRevision: 2 })).status, 403);
assert.equal((await api(`sections?album=${album.id}`, outsider)).status, 404);
assert.equal((await api('sections', owner, 'POST', { albumId: album.id, name: 'ceremony', expectedRevision: (await albumState(album.id)).revision })).status, 409);
assert.equal((await api('sections', owner, 'POST', { albumId: album.id, name: 'Stale', expectedRevision: 0 })).status, 409);
assert.equal((await albumState(album.id)).revision, 2);
const bytes = Buffer.from('Exact original and metadata remain unchanged through section placement.');
const manifest = () => ({ id: randomUUID(), name: 'camera.raw', mime: 'application/octet-stream', size: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex'), category: 'original', albumId: album.id, sectionId: ceremony.id });

// Real multipart fixtures exercise destination capture and preserve original download bytes.
async function uploadSectionFile() {
  const input = manifest();
  await json(await api('uploads', member, 'POST', input));
  const part = await json(await api(`uploads/${input.id}/part`, member, 'POST', { number: 1 }));
  const uploaded = await fetch(new URL(part.url, origin), { method: 'PUT', headers: { Cookie: member, Origin: origin }, body: bytes });
  assert.equal(uploaded.status, 200);
  await json(await api(`uploads/${input.id}/complete`, member, 'POST', { parts: [{ partNumber: 1, etag: uploaded.headers.get('etag').replaceAll('"', '') }] }));
  return input.id;
}
const first = await uploadSectionFile();
const second = await uploadSectionFile();
const feed = async (albumId = album.id, section = '') => json(await api(`feed?album=${albumId}&section=${section}`, owner));
const selection = async ids => (await feed()).items.filter(file => ids.includes(file.id)).map(file => ({ id: file.id, expectedRevision: file.revision }));
assert.equal((await feed(album.id, ceremony.id)).total, 2);
assert.equal((await feed(album.id, 'unsectioned')).total, 0);
assert.equal((await api(`feed?section=${ceremony.id}`, owner)).status, 400);
assert.equal((await api(`feed?album=${album.id}&section=${portfolio.id}`, owner)).status, 404);
assert.equal((await api('uploads', member, 'POST', { ...manifest(), sectionId: portfolio.id })).status, 409);
await json(await api('library/organise', owner, 'POST', { action: 'add', albumId: secondAlbum.id, files: await selection([first]) }));
const move = async (files, albumId = album.id, actor = owner) => api('library/sections', actor, 'POST', { albumId, files });
const moveInput = (await selection([first, second])).map(file => ({ ...file, sectionId: shortlist.id }));
assert.equal((await move(moveInput, album.id, member)).status, 403);
assert.equal((await move(moveInput, album.id, outsider)).status, 409);
const moved = await json(await move(moveInput));
assert.equal((await feed(album.id, shortlist.id)).total, 2);
assert.equal((await feed(secondAlbum.id, 'unsectioned')).total, 1);
assert.equal((await move(moveInput)).status, 409, 'Stale move must not partially apply.');
await json(await move(moved.previous));
assert.equal((await feed(album.id, ceremony.id)).total, 2);
const mixed = (await selection([first, second])).map((file, index) => ({ ...file, sectionId: index ? portfolio.id : shortlist.id }));
assert.equal((await move(mixed)).status, 409);
assert.equal((await feed(album.id, ceremony.id)).total, 2, 'Invalid destination aborts every placement.');
const removed = await json(await api(`sections/${ceremony.id}`, owner, 'PUT', { albumId: album.id, name: 'Ceremony', expectedRevision: (await albumState(album.id)).revision, deleted: true }));
assert.equal((await feed(album.id, 'unsectioned')).total, 2);
assert.equal((await api('uploads', member, 'POST', manifest())).status, 409);
await json(await move((await selection([first])).map(file => ({ ...file, sectionId: shortlist.id }))));
await json(await api(`sections/${ceremony.id}`, owner, 'PUT', { albumId: album.id, name: 'Ceremony', expectedRevision: removed.revision, deleted: false }));
assert.equal((await feed(album.id, ceremony.id)).total, 1, 'Restore must not overwrite a subsequent explicit move.');
assert.equal((await feed(album.id, shortlist.id)).total, 1);
const raceRevision = (await albumState(album.id)).revision;
const race = await Promise.all(['Reception', 'References'].map(name => api('sections', owner, 'POST', { albumId: album.id, name, expectedRevision: raceRevision })));
assert.deepEqual(race.map(response => response.status).sort(), [200, 409]);
assert.deepEqual(Buffer.from(await (await api(`media/${first}/download`, owner)).arrayBuffer()), bytes);
const removedMembership = await json(await api('library/organise', owner, 'POST', { action: 'remove', albumId: album.id, files: await selection([first]) }));
await json(await api('library/organise', owner, 'POST', { action: 'add', albumId: album.id, files: removedMembership.files.map(file => ({ id: file.id, expectedRevision: file.revision, sectionId: removedMembership.changed[0].sectionId })) }));
assert.equal((await feed(album.id, shortlist.id)).total, 1, 'Undo album removal restores section placement.');
const beforeOrder = await json(await api(`sections?album=${album.id}`, owner));
const reversed = beforeOrder.sections.map(section => section.id).reverse();
await json(await api('sections/order', owner, 'POST', { albumId: album.id, expectedRevision: beforeOrder.revision, ids: reversed }));
assert.deepEqual((await json(await api(`sections?album=${album.id}`, owner))).sections.map(section => section.id), reversed);
assert.equal((await api('sections/order', owner, 'POST', { albumId: album.id, expectedRevision: beforeOrder.revision, ids: reversed })).status, 409);
const templateAlbum = await json(await api('albums', owner, 'POST', { name: 'Template preview' }));
await json(await api('library/organise', owner, 'POST', { action: 'add', albumId: templateAlbum.id, files: await selection([first, second]) }));
const templateFiles = await selection([first, second]);
const template = await json(await api('sections/template', owner, 'POST', { albumId: templateAlbum.id, expectedRevision: 0, files: templateFiles }));
const templateSections = (await json(await api(`sections?album=${templateAlbum.id}`, owner))).sections;
assert.deepEqual(templateSections.map(section => section.name), ['Originals', 'Final cuts']);
assert.equal((await feed(templateAlbum.id, templateSections[0].id)).total, 2);
assert.equal((await feed(album.id, shortlist.id)).total, 1, 'Template mapping is album-local.');
await json(await move(template.files.map(file => ({ id: file.id, expectedRevision: file.revision, sectionId: null })), templateAlbum.id));
assert.equal((await feed(templateAlbum.id, 'unsectioned')).total, 2);
assert.equal((await api('sections/template', owner, 'POST', { albumId: templateAlbum.id, expectedRevision: 1, files: [] })).status, 409, 'Templates cannot replace existing active sections.');
console.log('PASS: section destinations, counts, multi-album isolation, permissions, name conflicts, concurrent revisions, atomic moves/Undo, soft removal/restoration and original bytes.');
